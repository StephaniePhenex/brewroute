-- Issue #1 — BrewRoute core schema.
-- Tables, CHECK constraints, single-ACTIVE index, soft-delete guard.
-- Stored text never contains '<' or '>' (CLAUDE.md A03): Zod strips them in
-- the action layer and these CHECKs reject anything that slips through.

create schema if not exists private;

create type public.app_role as enum ('USER', 'ADMIN');
create type public.season_status as enum ('DRAFT', 'ACTIVE', 'ARCHIVED');

-- ---------------------------------------------------------------------------
-- users: internal uuid PK; auth_subject is the identity provider's `sub`
-- (Google sub via Auth.js, or the Clerk user id). Rows are upserted
-- server-side at sign-in; role is never taken from the JWT.
-- ---------------------------------------------------------------------------
create table public.users (
  id uuid primary key default gen_random_uuid(),
  auth_subject text not null,
  display_name text not null,
  role public.app_role not null default 'USER',
  created_at timestamptz not null default now(),
  constraint users_auth_subject_key unique (auth_subject),
  constraint users_auth_subject_check check (char_length(auth_subject) between 1 and 255),
  constraint users_display_name_check check (
    char_length(btrim(display_name)) >= 1
    and char_length(display_name) <= 80
    and display_name !~ '[<>]'
  )
);

-- ---------------------------------------------------------------------------
-- seasons (AC 1.3–1.6, 3.2, 3.5)
-- ---------------------------------------------------------------------------
create table public.seasons (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  theme text not null default '',
  status public.season_status not null default 'DRAFT',
  min_checkins integer not null,
  winner_count integer not null,
  public_seed text not null,
  pool_snapshot jsonb,
  winners jsonb,
  raffle_drawn_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint seasons_name_check check (
    char_length(btrim(name)) >= 3
    and char_length(name) <= 80
    and name !~ '[<>]'
  ),
  constraint seasons_theme_check check (char_length(theme) <= 200 and theme !~ '[<>]'),
  constraint seasons_min_checkins_check check (min_checkins >= 1),
  constraint seasons_winner_count_check check (winner_count >= 1),
  -- Default seed is <NAME-SLUG(<=16)>-<YEAR> (generated by createSeason).
  constraint seasons_public_seed_check check (
    char_length(public_seed) between 1 and 64
    and public_seed !~ '[<>]'
  ),
  constraint seasons_pool_snapshot_array check (
    pool_snapshot is null or jsonb_typeof(pool_snapshot) = 'array'
  ),
  constraint seasons_winners_array check (
    winners is null or jsonb_typeof(winners) = 'array'
  ),
  -- A draw is persisted atomically: all three set, or none.
  constraint seasons_draw_consistency check (
    (raffle_drawn_at is null) = (pool_snapshot is null)
    and (raffle_drawn_at is null) = (winners is null)
  )
);

-- ADR-2 / AC 1.6: at most one ACTIVE season. "Exactly one" is maintained by
-- public.activate_season(), which archives the old row in the same transaction.
create unique index seasons_single_active
  on public.seasons ((true))
  where status = 'ACTIVE';

-- ---------------------------------------------------------------------------
-- cafes (AC 2.2, 2.5–2.8)
-- ---------------------------------------------------------------------------
create table public.cafes (
  id uuid primary key default gen_random_uuid(),
  season_id uuid not null references public.seasons (id) on delete restrict,
  name text not null,
  address text not null,
  latitude double precision not null,
  longitude double precision not null,
  tags text[] not null,
  sort_order integer not null,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint cafes_name_check check (
    char_length(btrim(name)) >= 1
    and char_length(name) <= 80
    and name !~ '[<>]'
  ),
  constraint cafes_address_check check (
    char_length(btrim(address)) >= 1
    and char_length(address) <= 200
    and address !~ '[<>]'
  ),
  constraint cafes_latitude_check check (latitude between -90 and 90),
  constraint cafes_longitude_check check (longitude between -180 and 180),
  constraint cafes_tags_check check (
    cardinality(tags) >= 1
    and array_position(tags, null) is null
    and not ('' = any (tags))
    and array_to_string(tags, ' ') !~ '[<>]'
  ),
  constraint cafes_sort_order_check check (sort_order >= 0),
  -- Deferred so stops can be reordered by swapping inside one transaction.
  constraint cafes_season_sort_order_key unique (season_id, sort_order)
    deferrable initially deferred,
  -- Target of the composite FK from reviews.
  constraint cafes_id_season_key unique (id, season_id)
);

-- ---------------------------------------------------------------------------
-- reviews (AC 5.2–5.5, 6.2–6.4)
-- Note length is enforced here AND in Zod (lib/validations/review.ts, Issue #7).
-- ---------------------------------------------------------------------------
create table public.reviews (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.users (id) on delete restrict,
  cafe_id uuid not null,
  season_id uuid not null,
  coffee_quality smallint not null,
  ambiance smallint not null,
  workspace_friendliness smallint not null,
  note text not null,
  created_at timestamptz not null default now(),
  -- A review's season must be its café's season.
  constraint reviews_cafe_season_fkey foreign key (cafe_id, season_id)
    references public.cafes (id, season_id) on delete restrict,
  constraint reviews_coffee_quality_check check (coffee_quality between 1 and 5),
  constraint reviews_ambiance_check check (ambiance between 1 and 5),
  constraint reviews_workspace_friendliness_check check (workspace_friendliness between 1 and 5),
  constraint reviews_note_check check (
    char_length(note) between 10 and 500
    and note = btrim(note)
    and note !~ '[<>]'
  )
);

-- Raffle eligibility: COUNT(DISTINCT cafe_id) per (season, user).
create index reviews_season_user_cafe_idx on public.reviews (season_id, user_id, cafe_id);
-- Archive: newest first.
create index reviews_created_at_idx on public.reviews (created_at desc);
create index reviews_user_id_idx on public.reviews (user_id);
create index reviews_cafe_season_idx on public.reviews (cafe_id, season_id);

-- ---------------------------------------------------------------------------
-- Triggers
-- ---------------------------------------------------------------------------
create function private.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create trigger seasons_touch_updated_at
  before update on public.seasons
  for each row execute function private.touch_updated_at();

create trigger cafes_touch_updated_at
  before update on public.cafes
  for each row execute function private.touch_updated_at();

-- ADR-3: cafés are never hard-deleted, not even by the secret key.
create function private.prevent_cafe_hard_delete()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  raise exception 'cafes are soft-deleted: set deleted_at instead of DELETE (cafe %)', old.id;
end;
$$;

create trigger cafes_no_hard_delete
  before delete on public.cafes
  for each row execute function private.prevent_cafe_hard_delete();
